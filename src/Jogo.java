//PASSO 2 - a classe Jogo.

public class Jogo {
    String nome;
    double nota;
    String lançamento;
    String generos;
    String plataformas;
    String imagems;

    public Jogo (String nome, double nota, String lançamento, String generos, String plataformas, String imagems) {
        this.nome = nome;
        this.nota = nota;
        this.lançamento = lançamento;
        this.generos = generos;
        this.plataformas = plataformas;
        this.imagems = imagems;
    }

}
